package youtubemusic

import (
	"reflect"
	"testing"

	"github.com/DonDevCode/music-translator/internal/platform"
)

func TestParseSnippet(t *testing.T) {
	tests := []struct {
		name string
		in   snippet
		want platform.Track
	}{
		{
			name: "auto-generated",
			in: snippet{
				Title:        "Bohemian Rhapsody (Live Aid)",
				ChannelTitle: "Queen - Topic",
				Description:  "Provided to YouTube by Columbia\n\nBohemian Rhapsody (Live Aid) · Queen\n\nBohemian Rhapsody\n\n℗ 2018 Queen Productions Ltd\n\nReleased on: 2018-10-19\n\nAuto-generated by YouTube.",
			},
			want: platform.Track{Title: "Bohemian Rhapsody (Live Aid)", Artists: []string{"Queen"}, Year: 2018},
		},
		{
			name: "auto-generated with multiple artists",
			in: snippet{
				Title:        "Under Pressure",
				ChannelTitle: "Queen - Topic",
				Description:  "Provided to YouTube by EMI\n\nUnder Pressure · Queen · David Bowie\n\nHot Space\n\n℗ 1981 Queen Productions Ltd\n\nReleased on: 1981-10-26\n\nAuto-generated by YouTube.",
			},
			want: platform.Track{Title: "Under Pressure", Artists: []string{"Queen", "David Bowie"}, Year: 1981},
		},
		{
			name: "auto-generated without release date",
			in: snippet{
				Title:        "Song",
				ChannelTitle: "Artist - Topic",
				Description:  "Provided to YouTube by DistroKid\n\nSong · Artist\n\nAlbum\n\n℗ 2021 Artist\n\nAuto-generated by YouTube.",
			},
			want: platform.Track{Title: "Song", Artists: []string{"Artist"}, Year: 2021},
		},
		{
			name: "topic channel without auto-generated description",
			in:   snippet{Title: "Bohemian Rhapsody - Remastered 2011", ChannelTitle: "Queen - Topic"},
			want: platform.Track{Title: "Bohemian Rhapsody - Remastered 2011", Artists: []string{"Queen"}},
		},
		{
			name: "official video with en dash",
			in: snippet{
				Title:        "Queen – Bohemian Rhapsody (Official Video Remastered)",
				ChannelTitle: "Queen Official",
				Description:  "REMASTERED IN HD TO CELEBRATE ONE BILLION VIEWS!",
			},
			want: platform.Track{Title: "Bohemian Rhapsody", Artists: []string{"Queen"}},
		},
		{
			name: "feat in title",
			in:   snippet{Title: "Mark Ronson - Uptown Funk (Official Video) ft. Bruno Mars", ChannelTitle: "Mark Ronson"},
			want: platform.Track{Title: "Uptown Funk", Artists: []string{"Mark Ronson", "Bruno Mars"}},
		},
		{
			name: "bracketed feat",
			in:   snippet{Title: "Calvin Harris - This Is What You Came For [Official Video] (feat. Rihanna)", ChannelTitle: "CalvinHarrisVEVO"},
			want: platform.Track{Title: "This Is What You Came For", Artists: []string{"Calvin Harris", "Rihanna"}},
		},
		{
			name: "feat on artist side",
			in:   snippet{Title: "Artist ft. Guest - Song", ChannelTitle: "Artist"},
			want: platform.Track{Title: "Song", Artists: []string{"Artist", "Guest"}},
		},
		{
			name: "no separator falls back to channel",
			in:   snippet{Title: "Blinding Lights (Official Audio)", ChannelTitle: "TheWeekndVEVO"},
			want: platform.Track{Title: "Blinding Lights", Artists: []string{"TheWeeknd"}},
		},
		{
			name: "pipe suffix and quotes",
			in:   snippet{Title: `Artist - "Song" | Live at Somewhere`, ChannelTitle: "Artist"},
			want: platform.Track{Title: "Song", Artists: []string{"Artist"}},
		},
		{
			name: "keeps non-tag brackets",
			in:   snippet{Title: "Queen - Bohemian Rhapsody (Live Aid 1985)", ChannelTitle: "Live Aid"},
			want: platform.Track{Title: "Bohemian Rhapsody (Live Aid 1985)", Artists: []string{"Queen"}},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := parseSnippet(tt.in)
			if !reflect.DeepEqual(*got, tt.want) {
				t.Errorf("parseSnippet = %+v, want %+v", *got, tt.want)
			}
		})
	}
}
