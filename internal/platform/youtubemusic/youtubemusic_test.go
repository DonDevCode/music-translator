func TestParseURL(t *testing.T) {
	tests := []struct {
		url    string
		wantID string
		wantOK bool
	}{
		{"https://music.youtube.com/watch?v=kM0Fpbz0W8U", "kM0Fpbz0W8U", true},
		{"https://music.youtube.com/watch?v=kM0Fpbz0W8U&si=abc123", "kM0Fpbz0W8U", true},
		{"https://music.youtube.com/watch?v=a-b_c-d_e-f&list=RDAMVM", "a-b_c-d_e-f", true},
		{"https://music.youtube.com/watch?v=tooshort", "", false},
		{"https://music.youtube.com/watch", "", false},
		{"https://music.youtube.com/playlist?list=PL123", "", false},
		{"https://music.youtube.com/channel/UC123", "", false},
		{"https://www.youtube.com/watch?v=kM0Fpbz0W8U", "", false},
		{"https://youtu.be/kM0Fpbz0W8U", "", false},
	}

	c := New(http.DefaultClient, "key")
	for _, tt := range tests {
		u, err := url.Parse(tt.url)
		if err != nil {
			t.Fatal(err)
		}
		id, ok := c.ParseURL(u)
		if id != tt.wantID || ok != tt.wantOK {
			t.Errorf("ParseURL(%q) = %q, %v; want %q, %v", tt.url, id, ok, tt.wantID, tt.wantOK)
		}
	}
}

// Trimmed real response for videos.list?part=snippet&id=kM0Fpbz0W8U.
const videosFixture = `{
  "items": [{
    "id": "kM0Fpbz0W8U",
    "snippet": {
      "publishedAt": "2026-06-30T10:00:31Z",
      "title": "Bohemian Rhapsody (Live Aid)",
      "description": "Provided to YouTube by Columbia\n\nBohemian Rhapsody (Live Aid) · Queen\n\nBohemian Rhapsody\n\n℗ 2018 Queen Productions Ltd\n\nReleased on: 2018-10-19\n\nLyricist, Vocal, Composer: Freddie Mercury\n\nAuto-generated by YouTube.",
      "channelTitle": "Queen - Topic",
      "categoryId": "10"
    }
  }]
}`

func TestLookup(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		q := r.URL.Query()
		if r.URL.Path != "/videos" || q.Get("key") != "secret" || q.Get("part") != "snippet" {
			t.Errorf("unexpected request %s", r.URL)
		}
		if q.Get("id") == "kM0Fpbz0W8U" {
			w.Write([]byte(videosFixture))
		} else {
			w.Write([]byte(`{"items":[]}`))
		}
	}))
	defer srv.Close()

	c := New(srv.Client(), "secret")
	c.baseURL = srv.URL

	got, err := c.Lookup(context.Background(), "kM0Fpbz0W8U")
	if err != nil {
		t.Fatal(err)
	}
	want := &platform.Track{
		Title:   "Bohemian Rhapsody (Live Aid)",
		Artists: []string{"Queen"},
		Year:    2018,
		URL:     "https://music.youtube.com/watch?v=kM0Fpbz0W8U",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Lookup = %+v, want %+v", got, want)
	}

	if _, err := c.Lookup(context.Background(), "xxxxxxxxxxx"); !errors.Is(err, platform.ErrNotFound) {
		t.Errorf("Lookup of unknown video: err = %v, want ErrNotFound", err)
	}
}

// Search results, with titles HTML-escaped like the real API does. The music
// video ranks first, but the auto-generated track should be preferred.
const searchFixture = `{
  "items": [
    {"id": {"videoId": "fJ9rUzIMcZQ"}, "snippet": {"title": "Queen – Bohemian Rhapsody (Official Video Remastered)", "channelTitle": "Queen Official"}},
    {"id": {"videoId": "5zLnaNY58j8"}, "snippet": {"title": "Queen - Bohemian Rhapsody (Lyrics)", "channelTitle": "7clouds Rock"}},
    {"id": {"videoId": "yk3prd8GER4"}, "snippet": {"title": "Bohemian Rhapsody", "channelTitle": "Queen - Topic"}},
    {"id": {"videoId": "xxxxxxxxxxx"}, "snippet": {"title": "Don&#39;t Stop Me Now", "channelTitle": "Queen - Topic"}}
  ]
}`

func TestSearch(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		q := r.URL.Query()
		if r.URL.Path != "/search" || q.Get("key") != "secret" || q.Get("type") != "video" {
			t.Errorf("unexpected request %s", r.URL)
		}
		w.Write([]byte(searchFixture))
	}))
	defer srv.Close()

	c := New(srv.Client(), "secret")
	c.baseURL = srv.URL

	tests := []struct {
		title   string
		wantURL string // "" for ErrNotFound
	}{
		{"Bohemian Rhapsody", "https://music.youtube.com/watch?v=yk3prd8GER4"},
		{"Don't Stop Me Now", "https://music.youtube.com/watch?v=xxxxxxxxxxx"},
		{"Radio Ga Ga", ""},
	}

	for _, tt := range tests {
		got, err := c.Search(context.Background(), &platform.Track{Title: tt.title, Artists: []string{"Queen"}})
		if tt.wantURL == "" {
			if !errors.Is(err, platform.ErrNotFound) {
				t.Errorf("Search(%q): err = %v, want ErrNotFound", tt.title, err)
			}
			continue
		}
		if err != nil {
			t.Errorf("Search(%q): %v", tt.title, err)
			continue
		}
		if got.URL != tt.wantURL {
			t.Errorf("Search(%q) = %s, want %s", tt.title, got.URL, tt.wantURL)
		}
	}
}

func TestRateLimit(t *testing.T) {
	tests := []struct {
		name    string
		status  int
		body    string
		limited bool
	}{
		{"quota exceeded", http.StatusForbidden, `{"error":{"code":403,"errors":[{"domain":"youtube.quota","reason":"quotaExceeded"}]}}`, true},
		{"too many requests", http.StatusTooManyRequests, ``, true},
		{"api disabled", http.StatusForbidden, `{"error":{"code":403,"errors":[{"domain":"usageLimits","reason":"accessNotConfigured"}]}}`, false},
		{"bad key", http.StatusBadRequest, `{"error":{"code":400,"errors":[{"domain":"usageLimits","reason":"keyInvalid"}]}}`, false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				w.WriteHeader(tt.status)
				w.Write([]byte(tt.body))
			}))
			defer srv.Close()

			c := New(srv.Client(), "secret")
			c.baseURL = srv.URL

			for name, call := range map[string]func() error{
				"Lookup": func() error { _, err := c.Lookup(context.Background(), "kM0Fpbz0W8U"); return err },
				"Search": func() error {
					_, err := c.Search(context.Background(), &platform.Track{Title: "Song", Artists: []string{"Artist"}})
					return err
				},
			} {
				err := call()
				var rateLimitErr *platform.RateLimitError
				if errors.As(err, &rateLimitErr) != tt.limited {
					t.Errorf("%s: err = %v, want rate limited = %v", name, err, tt.limited)
				}
				if err == nil {
					t.Errorf("%s: err = nil, want an error", name)
				}
			}
		})
	}
}
