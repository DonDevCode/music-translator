// innerTubeRow builds a search result row like those in InnerTube album
// searches, e.g. title "Abbey Road (2019 Mix)" with detail runs "Album",
// " • ", "The Beatles", " • ", "1969".
func innerTubeRow(playlistID, title string, details ...string) string {
	runs := make([]string, len(details))
	for i, d := range details {
		runs[i] = fmt.Sprintf(`{"text":%q}`, d)
	}
	return fmt.Sprintf(`{"musicResponsiveListItemRenderer":{
  "flexColumns":[
    {"musicResponsiveListItemFlexColumnRenderer":{"text":{"runs":[{"text":%q}]}}},
    {"musicResponsiveListItemFlexColumnRenderer":{"text":{"runs":[%s]}}}],
  "overlay":{"musicItemThumbnailOverlayRenderer":{"content":{"musicPlayButtonRenderer":{
    "playNavigationEndpoint":{"watchPlaylistEndpoint":{"playlistId":%q}}}}}}}}`,
		title, strings.Join(runs, ","), playlistID)
}

// innerTubeSearch wraps rows like a real InnerTube search response, which
// has an info message before the results.
func innerTubeSearch(rows ...string) string {
	return `{"contents":{"tabbedSearchResultsRenderer":{"tabs":[{"tabRenderer":{"content":{"sectionListRenderer":{"contents":[
  {"itemSectionRenderer":{}},
  {"musicShelfRenderer":{"contents":[` + strings.Join(rows, ",") + `]}}]}}}}]}}}`
}

