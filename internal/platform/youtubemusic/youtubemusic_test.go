func TestLookup(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		q := r.URL.Query()
		if r.URL.Path != "/videos" || q.Get("key") != "secret" || q.Get("part") != "snippet" {
			t.Errorf("unexpected request %s", r.URL)
		}
		if q.Get("id") == "kM0Fpbz0W8U" {
			w.Write([]byte(videosFixture))
		} else {
			w.Write([]byte(`{"items":[]}`))
		}
	}))
	defer srv.Close()

	c := New(srv.Client(), "secret")
	c.baseURL = srv.URL

	got, err := c.Lookup(context.Background(), "kM0Fpbz0W8U")
	if err != nil {
		t.Fatal(err)
	}
	want := &platform.Track{
		Title:   "Bohemian Rhapsody (Live Aid)",
		Artists: []string{"Queen"},
		Year:    2018,
		URL:     "https://music.youtube.com/watch?v=kM0Fpbz0W8U",
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Lookup = %+v, want %+v", got, want)
	}

	if _, err := c.Lookup(context.Background(), "xxxxxxxxxxx"); !errors.Is(err, platform.ErrNotFound) {
		t.Errorf("Lookup of unknown video: err = %v, want ErrNotFound", err)
	}
}

