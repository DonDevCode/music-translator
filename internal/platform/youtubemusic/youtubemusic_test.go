// innerTubeNext builds a response of the InnerTube next endpoint for a
// video, with the byline split into runs like the real one.
func innerTubeNext(videoID, videoType, title string, byline ...string) string {
	runs := make([]string, len(byline))
	for i, b := range byline {
		runs[i] = fmt.Sprintf(`{"text":%q}`, b)
	}
	return fmt.Sprintf(`{"contents":{"singleColumnMusicWatchNextResultsRenderer":{"tabbedRenderer":{"watchNextTabbedResultsRenderer":{"tabs":[
  {"tabRenderer":{"content":{"musicQueueRenderer":{"content":{"playlistPanelRenderer":{"contents":[
    {"playlistPanelVideoRenderer":{
      "videoId":%q,
      "title":{"runs":[{"text":%q}]},
      "longBylineText":{"runs":[%s]},
      "navigationEndpoint":{"watchEndpoint":{"videoId":%[1]q,"watchEndpointMusicSupportedConfigs":{"watchEndpointMusicConfig":{"musicVideoType":%[4]q}}}}}}]}}}}}},
  {"tabRenderer":{"title":"Lyrics"}}]}}}}}`,
		videoID, title, strings.Join(runs, ","), videoType)
}

// innerTubeTrackRow builds a song search result row that plays the track
// with the given video ID.
func innerTubeTrackRow(videoID, title, details string) string {
	return fmt.Sprintf(`{"musicResponsiveListItemRenderer":{
  "flexColumns":[
    {"musicResponsiveListItemFlexColumnRenderer":{"text":{"runs":[{"text":%q}]}}},
    {"musicResponsiveListItemFlexColumnRenderer":{"text":{"runs":[{"text":%q}]}}}],
  "overlay":{"musicItemThumbnailOverlayRenderer":{"content":{"musicPlayButtonRenderer":{
    "playNavigationEndpoint":{"watchEndpoint":{"videoId":%q}}}}}}}}`,
		title, details, videoID)
}

func TestLookupVideo(t *testing.T) {
	video := func(id, title, channel, category string) string {
		return fmt.Sprintf(`{"items":[{"id":%q,"snippet":{"title":%q,"channelTitle":%q,"description":"","categoryId":%q}}]}`,
			id, title, channel, category)
	}
	videos := map[string]string{
		// Real details of an official music video and its song's track.
		"fJ9rUzIMcZQ": video("fJ9rUzIMcZQ", "Queen – Bohemian Rhapsody (Official Video Remastered)", "Queen Official", "10"),
		"yk3prd8GER4": `{"items":[` + autoGenerated("yk3prd8GER4", "Bohemian Rhapsody", "Queen") + `]}`,
		// A music video whose song YouTube Music doesn't have.
		"omvnotrack0": video("omvnotrack0", "Band - Rare Song (Official Video)", "Band", "10"),
		// A cover in the Music category, and videos that aren't music.
		"cover000000": video("cover000000", "Artist - Song (Cover)", "Someone", "10"),
		"jNQXAC9IVRw": video("jNQXAC9IVRw", "Me at the zoo", "jawed", "22"),
		"brokenITube": video("brokenITube", "Vlog", "Someone", "22"),
		"brokenMusic": video("brokenMusic", "Artist - Song", "Artist", "10"),
	}
	next := map[string]string{
		"fJ9rUzIMcZQ": innerTubeNext("fJ9rUzIMcZQ", musicVideoType, "Bohemian Rhapsody", "Queen", " • ", "2.1B views", " • ", "14M likes"),
		"omvnotrack0": innerTubeNext("omvnotrack0", musicVideoType, "Rare Song", "Band", " • ", "12K views"),
		"cover000000": innerTubeNext("cover000000", "MUSIC_VIDEO_TYPE_UGC", "Artist - Song (Cover)", "Someone", " • ", "1K views"),
		"jNQXAC9IVRw": innerTubeNext("jNQXAC9IVRw", "MUSIC_VIDEO_TYPE_UGC", "Me at the zoo", "jawed", " • ", "448M views"),
	}
	songs := innerTubeSearch(
		innerTubeTrackRow("otherQueen0", "Bohemian Rhapsody (Live Aid)", "Queen • Bohemian Rhapsody • 5:52"),
		innerTubeTrackRow("yk3prd8GER4", "Bohemian Rhapsody", "Queen • A Night At The Opera • 5:55"),
	)

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/videos":
			if body, ok := videos[r.URL.Query().Get("id")]; ok {
				w.Write([]byte(body))
			} else {
				w.Write([]byte(`{"items":[]}`))
			}
		case "/innertube/next":
			var req struct {
				VideoID string `json:"videoId"`
			}
			json.NewDecoder(r.Body).Decode(&req)
			if strings.HasPrefix(req.VideoID, "broken") {
				http.Error(w, "oops", http.StatusInternalServerError)
				return
			}
			w.Write([]byte(next[req.VideoID]))
		case "/innertube/search":
			var req struct {
				Query  string `json:"query"`
				Params string `json:"params"`
			}
			json.NewDecoder(r.Body).Decode(&req)
			if req.Params != songsFilter {
				t.Errorf("searched with params %q, want songs", req.Params)
			}
			if req.Query == "Queen Bohemian Rhapsody" {
				w.Write([]byte(songs))
			} else {
				w.Write([]byte(innerTubeSearch()))
			}
		default:
			t.Errorf("unexpected request %s", r.URL)
		}
	}))
	defer srv.Close()

	c := New(srv.Client(), "secret")
	c.baseURL = srv.URL
	c.innerTubeURL = srv.URL + "/innertube"

	tests := []struct {
		id      string
		want    *platform.Track // nil for ErrNotMusic
		wantAny *platform.Track // the result of Lookup if it differs
	}{
		{"fJ9rUzIMcZQ", &platform.Track{Title: "Bohemian Rhapsody", Artists: []string{"Queen"}, Year: 2020, URL: "https://music.youtube.com/watch?v=yk3prd8GER4"}, nil},
		{"omvnotrack0", &platform.Track{Title: "Rare Song", Artists: []string{"Band"}, URL: "https://music.youtube.com/watch?v=omvnotrack0"}, nil},
		{"cover000000", &platform.Track{Title: "Song (Cover)", Artists: []string{"Artist"}, URL: "https://music.youtube.com/watch?v=cover000000"}, nil},
		{"brokenMusic", &platform.Track{Title: "Song", Artists: []string{"Artist"}, URL: "https://music.youtube.com/watch?v=brokenMusic"}, nil},
		{"jNQXAC9IVRw", nil, &platform.Track{Title: "Me at the zoo", Artists: []string{"jawed"}, URL: "https://music.youtube.com/watch?v=jNQXAC9IVRw"}},
		{"brokenITube", nil, &platform.Track{Title: "Vlog", Artists: []string{"Someone"}, URL: "https://music.youtube.com/watch?v=brokenITube"}},
	}

	for _, tt := range tests {
		got, err := c.LookupVideo(context.Background(), tt.id)
		if tt.want == nil {
			if !errors.Is(err, platform.ErrNotMusic) {
				t.Errorf("LookupVideo(%s): err = %v, want ErrNotMusic", tt.id, err)
			}
		} else if err != nil {
			t.Errorf("LookupVideo(%s): %v", tt.id, err)
		} else if !reflect.DeepEqual(got, tt.want) {
			t.Errorf("LookupVideo(%s) = %+v, want %+v", tt.id, got, tt.want)
		}

		// Links to YouTube Music are music, whatever the video is.
		want := tt.want
		if tt.wantAny != nil {
			want = tt.wantAny
		}
		got, err = c.Lookup(context.Background(), tt.id)
		if err != nil {
			t.Errorf("Lookup(%s): %v", tt.id, err)
		} else if !reflect.DeepEqual(got, want) {
			t.Errorf("Lookup(%s) = %+v, want %+v", tt.id, got, want)
		}
	}

	if _, err := c.LookupVideo(context.Background(), "xxxxxxxxxxx"); !errors.Is(err, platform.ErrNotFound) {
		t.Errorf("LookupVideo of unknown video: err = %v, want ErrNotFound", err)
	}
}

