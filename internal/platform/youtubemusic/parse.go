package youtubemusic

import (
	"html"
	"regexp"
	"strings"

	"github.com/DonDevCode/music-translator/internal/platform"
)

var (
	// Bracketed title suffixes like "(Official Video)" or "[Lyrics]".
	tagPattern = regexp.MustCompile(`(?i)\s*[(\[][^)\]]*\b(official|video|audio|lyrics?|visuali[sz]er|hd|hq|4k|remaster(ed)?|m/?v)\b[^)\]]*[)\]]`)
	// Featured artists, optionally bracketed: "(feat. X)", "ft. X".
	featPattern = regexp.MustCompile(`(?i)\s*[(\[]?\b(?:feat\.?|ft\.?|featuring)\s+([^)\]]+?)\s*(?:[)\]]|$)`)
	// "Artist - Title" separators, including en and em dashes.
	separatorPattern = regexp.MustCompile(`\s[-–—]\s`)
	// Channel name suffixes that aren't part of the artist name.
	channelSuffixPattern = regexp.MustCompile(`(?i)(\s*-\s*Topic|\s*VEVO|\s+Official)$`)
	copyrightYearPattern = regexp.MustCompile(`^℗ (\d{4})\b`)
)

// parseSnippet extracts track details from a video's snippet. Videos that
// YouTube generates automatically for official releases (on "Artist - Topic"
// channels) have a fixed description format with exact data. For all other
// videos the title and channel name are cleaned up as well as possible.
func parseSnippet(s snippet) *platform.Track {
	if t := parseAutoGenerated(s); t != nil {
		return t
	}
	if isTopicChannel(s.ChannelTitle) {
		return topicTrack(s.Title, s.ChannelTitle)
	}
	return parseTitle(s.Title, s.ChannelTitle)
}

// parseSearchResult extracts track details from a search result's snippet,
// whose title is HTML-escaped and whose description is truncated.
func parseSearchResult(s snippet) *platform.Track {
	title := html.UnescapeString(s.Title)
	channel := html.UnescapeString(s.ChannelTitle)

	if isTopicChannel(channel) {
		return topicTrack(title, channel)
	}
	return parseTitle(title, channel)
}

func isTopicChannel(channel string) bool {
	return strings.HasSuffix(channel, " - Topic")
}

// topicTrack derives the track from an auto-generated video's title and
// channel. Such videos are titled with just the song name, which may itself
// contain " - " (e.g. "Song - Remastered 2011"), so it isn't split.
func topicTrack(title, channel string) *platform.Track {
	return &platform.Track{
		Title:   title,
		Artists: []string{channelSuffixPattern.ReplaceAllString(channel, "")},
	}
}

// parseAutoGenerated parses descriptions of this form:
//
//	Provided to YouTube by Columbia
//
//	Bohemian Rhapsody · Queen
//
//	A Night At The Opera
//
//	℗ 1975 Queen Productions Ltd
//
//	Released on: 1975-11-21
//
// It returns nil if the description doesn't match.
func parseAutoGenerated(s snippet) *platform.Track {
	lines := strings.Split(s.Description, "\n")
	if len(lines) == 0 || !strings.HasPrefix(lines[0], "Provided to YouTube by") {
		return nil
	}

	var t platform.Track
	for _, line := range lines[1:] {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}

		switch {
		case t.Title == "":
			// First non-empty line: "Title · Artist · Artist".
			parts := strings.Split(line, " · ")
			if len(parts) < 2 {
				return nil
			}
			t.Title = strings.TrimSpace(parts[0])
			for _, a := range parts[1:] {
				t.Artists = append(t.Artists, strings.TrimSpace(a))
			}
		case strings.HasPrefix(line, "Released on: "):
			// The release date is more accurate than the copyright year.
			t.Year = platform.ParseYear(strings.TrimPrefix(line, "Released on: "))
		case t.Year == 0:
			if m := copyrightYearPattern.FindStringSubmatch(line); m != nil {
				t.Year = platform.ParseYear(m[1])
			}
		}
	}

	if t.Title == "" {
		return nil
	}
	return &t
}

// parseTitle derives the track from titles like
// "Queen – Bohemian Rhapsody (Official Video Remastered)", falling back to the
// channel name as artist. The upload date says nothing about the release, so
// the year is left unknown.
func parseTitle(title, channel string) *platform.Track {
	title, _, _ = strings.Cut(title, " | ")
	title = tagPattern.ReplaceAllString(title, "")

	artist := channelSuffixPattern.ReplaceAllString(channel, "")
	if loc := separatorPattern.FindStringIndex(title); loc != nil {
		artist, title = title[:loc[0]], title[loc[1]:]
	}

	// Featured artists can appear on either side: "A ft. B - Song" or
	// "A - Song (feat. B)".
	artist, featArtist := cutFeatured(artist)
	title, featTitle := cutFeatured(title)

	t := &platform.Track{
		Title:   strings.Trim(title, `"'“”`),
		Artists: []string{artist},
	}
	for _, f := range []string{featArtist, featTitle} {
		if f != "" {
			t.Artists = append(t.Artists, f)
		}
	}
	return t
}

// cutFeatured removes a featured-artist clause from s and returns it
// separately.
func cutFeatured(s string) (rest, featured string) {
	m := featPattern.FindStringSubmatchIndex(s)
	if m == nil {
		return strings.TrimSpace(s), ""
	}
	rest = strings.TrimSpace(s[:m[0]] + " " + s[m[1]:])
	return rest, strings.TrimSpace(s[m[2]:m[3]])
}
